import { useEffect, useState } from 'react';

/**
 * Delays a fast-changing value so it can drive a request. Typing updates the
 * field on every keystroke; the query only follows once the user pauses.
 *
 * Lives here rather than beside one list page because every server-searched
 * listing needs it, and two copies would eventually disagree on the delay.
 */
export function useDebouncedValue<T>(value: T, delayMs: number): T {
  const [debounced, setDebounced] = useState(value);

  useEffect(() => {
    const timer = setTimeout(() => setDebounced(value), delayMs);
    return () => clearTimeout(timer);
  }, [value, delayMs]);

  return debounced;
}
