/**
 * Map over `items` with at most `limit` calls to `mapper` in flight at once.
 *
 * `Promise.all(items.map(mapper))` fires every call simultaneously — fine for
 * a handful of items, but a burst of requests once `items` is a full,
 * unpaged-from-the-server list (dozens to hundreds of entries). This runs a
 * small worker pool instead, preserving result order.
 */
export async function mapWithConcurrency<T, R>(
  items: T[],
  limit: number,
  mapper: (item: T, index: number) => Promise<R>
): Promise<R[]> {
  const results: R[] = new Array(items.length);
  let nextIndex = 0;

  async function worker(): Promise<void> {
    while (true) {
      const current = nextIndex++;
      if (current >= items.length) return;
      results[current] = await mapper(items[current], current);
    }
  }

  const workerCount = Math.max(1, Math.min(limit, items.length));
  await Promise.all(Array.from({ length: workerCount }, worker));

  return results;
}
