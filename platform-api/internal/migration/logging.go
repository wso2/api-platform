package migration

import (
	"log/slog"
	"os"
	"strings"
)

// NewLogger builds the structured logger. It NEVER receives plaintext secrets or
// decrypted tokens as attributes — callers must not pass them. This is the single
// place log output is configured so the redaction rule is enforceable by review.
func NewLogger(level, format string) *slog.Logger {
	var lvl slog.Level
	switch strings.ToLower(level) {
	case "debug":
		lvl = slog.LevelDebug
	case "warn":
		lvl = slog.LevelWarn
	case "error":
		lvl = slog.LevelError
	default:
		lvl = slog.LevelInfo
	}
	opts := &slog.HandlerOptions{Level: lvl}
	var h slog.Handler
	if strings.EqualFold(format, "json") {
		h = slog.NewJSONHandler(os.Stderr, opts)
	} else {
		h = slog.NewTextHandler(os.Stderr, opts)
	}
	return slog.New(h)
}

// redactKey returns a log-safe fingerprint of a secret key: never the bytes,
// only its presence and length. Use this instead of ever logging key material.
func redactKey(key []byte) string {
	if len(key) == 0 {
		return "<unset>"
	}
	return "<set:" + itoa(len(key)) + "B>"
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	return string(b[i:])
}
