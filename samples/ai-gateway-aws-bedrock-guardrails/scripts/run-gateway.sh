#!/usr/bin/env bash
# Starts the gateway with your temporary AWS credentials. start-gateway.sh runs it on first start.
# Run it again to restart the gateway with fresh credentials when your AWS session expires.
# Usage: ./scripts/run-gateway.sh <gateway-folder>
set -euo pipefail
# shellcheck source=scripts/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
GATEWAY_DIR="$(gateway_dir "${1:-}")"
CONFIG="${GATEWAY_DIR}/configs/config.toml"

# 1. Prepend the guardrail allowlist to config.toml (root-level keys go before the first [table]).
if ! grep -q '^awsbedrock_allowed_auth_types' "${CONFIG}"; then
  { envsubst "${SUBST_VARS}" < "${ROOT_DIR}/compose/allowlist.toml"; echo; cat "${CONFIG}"; } > "${CONFIG}.new"
  mv "${CONFIG}.new" "${CONFIG}"
fi

# 2. Build gateway images that include the newer guardrail policy (first run only).
if [ ! -f "${GATEWAY_DIR}/.sample-images" ]; then
  "${ROOT_DIR}/scripts/build-gateway-image.sh" "${GATEWAY_DIR}"
fi
# shellcheck disable=SC1091 # Written by build-gateway-image.sh.
source "${GATEWAY_DIR}/.sample-images"

# 3. Write the override: the built images, and your credentials for the runtime. Docker Compose
#    merges docker-compose.override.yaml automatically.
{
  echo "# Generated by run-gateway.sh from compose/docker-compose.override.yaml."
  echo "services:"
  echo "  gateway-controller:"
  echo "    image: ${CONTROLLER_IMAGE}"
  echo "  gateway-runtime:"
  echo "    image: ${RUNTIME_IMAGE}"
  sed -n '/^    environment:/,$p' "${ROOT_DIR}/compose/docker-compose.override.yaml"
} > "${GATEWAY_DIR}/docker-compose.override.yaml"

# 4. Export temporary credentials for this process only, and start the gateway with
#    the gateway's own command. Compose recreates only the containers whose settings changed,
#    such as the runtime when your credentials are new.
eval "$(aws configure export-credentials --format env)"
cd "${GATEWAY_DIR}"
gateway_compose up -d

# 5. Confirm the runtime received the credentials. Prints variable names only, never values.
runtime="$(gateway_compose ps -q gateway-runtime)"
names="$(docker inspect --format '{{range .Config.Env}}{{println .}}{{end}}' "${runtime}" | cut -d= -f1 | grep '^AWS_' | sort | tr '\n' ' ')"
case "${names}" in
  *AWS_SESSION_TOKEN*) echo "Gateway runtime has: ${names}" ;;
  *) echo "The gateway runtime has no AWS session credentials. Check that the service is named gateway-runtime." >&2; exit 1 ;;
esac

# 6. Leave the gateway running in the background. Set FOLLOW_LOGS=1 to follow its logs now.
echo "The gateway is running in the background. To follow its logs:"
echo "  (cd \"${GATEWAY_DIR}\" && docker compose --env-file .env --env-file api-platform.env logs -f)"
if [ "${FOLLOW_LOGS:-0}" = "1" ]; then
  gateway_compose logs -f --tail 20 gateway-controller gateway-runtime
fi
