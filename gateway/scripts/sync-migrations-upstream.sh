#!/usr/bin/env bash
#
# Open a PR on the public repo carrying the migration steps a release promoted.
#
#   sync-migrations-upstream.sh 2026.10.0
#
# A gateway release can be cut from wso2-enterprise/api-platform, but the
# migration steps have to reach wso2/api-platform too - otherwise the public
# chain has a gap and an operator upgrading past this release has no steps to
# apply. Nothing is pushed to a protected branch; this only opens a PR.
#
# Needs GH_TOKEN with repo scope on UPSTREAM_REPO.
set -euo pipefail

UPSTREAM_REPO="${UPSTREAM_REPO:-wso2/api-platform}"
UPSTREAM_BRANCH="${UPSTREAM_BRANCH:-main}"
MIGRATIONS_REL="gateway/gateway-controller/pkg/storage/migrations"

raw="${1:-}"
if [ -z "$raw" ]; then
  echo "usage: $(basename "$0") <version>" >&2
  exit 2
fi
release="${raw#gateway/}"; release="${release#ai-gateway/}"; release="${release#v}"

repo_root="$(cd "$(dirname "$0")/../.." && pwd)"
src="$repo_root/$MIGRATIONS_REL/$release"
if [ ! -d "$src" ]; then
  echo "no $MIGRATIONS_REL/$release - $release introduced no schema change, nothing to sync"
  exit 0
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

echo "cloning $UPSTREAM_REPO"
git clone --depth 1 --branch "$UPSTREAM_BRANCH" \
  "https://x-access-token:${GH_TOKEN}@github.com/${UPSTREAM_REPO}.git" "$work/repo" --quiet

cd "$work/repo"
mkdir -p "$MIGRATIONS_REL/$release" "$MIGRATIONS_REL/next"
cp "$src"/*.sql "$MIGRATIONS_REL/$release/"
# next/ is emptied by the promotion; keep the directory present upstream
find "$MIGRATIONS_REL/next" -maxdepth 1 -name '*.sql' -delete
touch "$MIGRATIONS_REL/next/.gitkeep"

if [ -z "$(git status --porcelain)" ]; then
  echo "$UPSTREAM_REPO already has $release - nothing to do"
  exit 0
fi

branch="gateway-migrations-${release}"
git checkout -q -b "$branch"
git config user.name "github-actions[bot]"
git config user.email "github-actions[bot]@users.noreply.github.com"
git add -A "$MIGRATIONS_REL"
git commit -qm "Add gateway migration steps for ${release}"
# The branch is bot-owned and regenerated from main every run, so a plain
# force push is correct. --force-with-lease cannot work here: the clone is
# shallow and has never seen this branch, so there is no lease to compare.
git push -q --force origin "HEAD:refs/heads/$branch"

if gh pr view "$branch" --repo "$UPSTREAM_REPO" >/dev/null 2>&1; then
  echo "PR already open for $branch, updated it"
  exit 0
fi

gh pr create --repo "$UPSTREAM_REPO" \
  --base "$UPSTREAM_BRANCH" --head "$branch" \
  --title "Gateway migration steps for ${release}" \
  --body "$(cat <<BODY
Migration steps promoted by the gateway ${release} release.

The release is cut elsewhere, so without this the public migration chain skips
${release} and an operator upgrading past it has no steps to apply.

Contents:
- \`${MIGRATIONS_REL}/${release}/\` - the steps this release introduced
- \`${MIGRATIONS_REL}/next/\` - emptied, ready for the next cycle

Generated by \`gateway/scripts/sync-migrations-upstream.sh\`.
BODY
)"
