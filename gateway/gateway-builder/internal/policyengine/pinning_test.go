const (
	pinnedModule = "github.com/example/policies/pinned"
	pinnedSum    = "h1:2YdNqRZ0DqUAXN1YoMm3UZ0fYtnb3wE7T8Yq1mQf7ac="
	otherSum     = "h1:AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
)

func pinnedPolicy(version, sum string) *types.DiscoveredPolicy {
	p := testutils.NewRemoteDiscoveredPolicy("pinned", version, pinnedModule, version)
	p.GoModuleSum = sum
	return p
}

func writePolicyEngineModule(t *testing.T, requireVersion, goSum string) string {
	t.Helper()
	dir := t.TempDir()
	testutils.WriteGoModWithRequire(t, dir, "github.com/example/policy-engine", "1.26.10", pinnedModule, requireVersion)
	testutils.WriteFile(t, filepath.Join(dir, "go.sum"), goSum)
	return dir
}

func TestVerifyPinnedGoModules_HappyPath(t *testing.T) {
	dir := writePolicyEngineModule(t, "v1.2.3",
		pinnedModule+" v1.2.3 "+pinnedSum+"\n"+
			pinnedModule+" v1.2.3/go.mod h1:BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB=\n")

	err := VerifyPinnedGoModules(dir, []*types.DiscoveredPolicy{pinnedPolicy("v1.2.3", pinnedSum)})

	assert.NoError(t, err)
}

func TestVerifyPinnedGoModules_VersionMovedByModuleGraph(t *testing.T) {
	// e.g. 'go mod tidy' selected a newer version required by another module.
	dir := writePolicyEngineModule(t, "v1.3.0", pinnedModule+" v1.3.0 "+otherSum+"\n")

	err := VerifyPinnedGoModules(dir, []*types.DiscoveredPolicy{pinnedPolicy("v1.2.3", pinnedSum)})

	require.Error(t, err)
	assert.Contains(t, err.Error(), "go.mod selects "+pinnedModule+"@v1.3.0")
}

func TestVerifyPinnedGoModules_GoSumMismatch(t *testing.T) {
	dir := writePolicyEngineModule(t, "v1.2.3", pinnedModule+" v1.2.3 "+otherSum+"\n")

	err := VerifyPinnedGoModules(dir, []*types.DiscoveredPolicy{pinnedPolicy("v1.2.3", pinnedSum)})

	require.Error(t, err)
	assert.Contains(t, err.Error(), "go.sum records "+otherSum)
}

func TestVerifyPinnedGoModules_MissingGoSumEntry(t *testing.T) {
	// Only the go.mod hash is present, not the module zip hash.
	dir := writePolicyEngineModule(t, "v1.2.3", pinnedModule+" v1.2.3/go.mod "+pinnedSum+"\n")

	err := VerifyPinnedGoModules(dir, []*types.DiscoveredPolicy{pinnedPolicy("v1.2.3", pinnedSum)})

	require.Error(t, err)
	assert.Contains(t, err.Error(), "go.sum has no entry")
}

func TestVerifyPinnedGoModules_SkipsLocalPolicies(t *testing.T) {
	dir := writePolicyEngineModule(t, "v1.2.3", "")
	local := testutils.NewLocalDiscoveredPolicy("local", "v1.0.0", "/tmp/local", "github.com/example/local")

	assert.NoError(t, VerifyPinnedGoModules(dir, []*types.DiscoveredPolicy{local}))
}

