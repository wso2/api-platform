func TestBaseConstraints(t *testing.T) {
	got := baseConstraints(sampleLock)

	assert.Equal(t,
		"apip-sdk-core==0.2.3\ngrpcio==1.85.1\ntyping-extensions==4.16.0 ; python_version < \"3.11\"\n",
		got)
	assert.Empty(t, baseConstraints(""))
}

func TestWritePythonRequirementFiles_SeparatesVerifiedBaseFromPolicies(t *testing.T) {
	out := t.TempDir()
	baseLock := filepath.Join(out, BaseRequirementsFile)
	testutils.WriteFile(t, baseLock, sampleLock)

	localDir := t.TempDir()
	testutils.WriteFile(t, filepath.Join(localDir, "requirements.txt"), "# deps\nslugify==0.0.1\n")

	gitSpec := "git+https://github.com/example/policies.git@5d9c02f471e8a388f99294ce7d09bf11b131e26c#subdirectory=policies/git-policy"
	policies := []*types.DiscoveredPolicy{
		{Name: "git-policy", Version: "v0.1.0", Runtime: "python", IsPipPackage: true, PipSpec: gitSpec},
		{
			Name: "indexed-policy", Version: "v1.0.0", Runtime: "python", IsPipPackage: true,
			PipSpec:     "indexed-policy==1.0.0@https://pypi.example.com/simple",
			PipIndexURL: "https://pypi.example.com/simple",
			PipChecksum: "sha256:5555555555555555555555555555555555555555555555555555555555555555",
		},
		{Name: "local-policy", Version: "v1.0.0", Runtime: "python", PythonSourceDir: localDir, Path: localDir},
	}

	require.NoError(t, writePythonRequirementFiles(out, policies))

	read := func(name string) string {
		data, err := os.ReadFile(filepath.Join(out, name))
		require.NoError(t, err)
		return string(data)
	}

	// The hash-pinned base lock is left exactly as committed.
	assert.Equal(t, sampleLock, read(BaseRequirementsFile))
	assert.Equal(t,
		"apip-sdk-core==0.2.3\ngrpcio==1.85.1\ntyping-extensions==4.16.0 ; python_version < \"3.11\"\n",
		read(BaseConstraintsFile))
	assert.Equal(t,
		"--extra-index-url https://pypi.example.com/simple\n"+
			"indexed-policy==1.0.0 --hash=sha256:5555555555555555555555555555555555555555555555555555555555555555\n",
		read(HashedPolicyRequirementsFile))
	assert.Equal(t,
		"--extra-index-url https://pypi.example.com/simple\n"+gitSpec+"\nindexed-policy==1.0.0\nslugify==0.0.1\n",
		read(PolicyRequirementsFile))
}

func TestWritePythonRequirementFiles_NoPythonPolicies(t *testing.T) {
	out := t.TempDir()
	testutils.WriteFile(t, filepath.Join(out, BaseRequirementsFile), sampleLock)

	require.NoError(t, writePythonRequirementFiles(out, nil))

	for _, name := range []string{PolicyRequirementsFile, HashedPolicyRequirementsFile} {
		data, err := os.ReadFile(filepath.Join(out, name))
		require.NoError(t, err, "%s must exist so the Docker COPY step succeeds", name)
		assert.Empty(t, string(data))
	}
}
