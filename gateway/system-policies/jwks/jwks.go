// Package jwks is the gateway's internal JWKS system policy. It answers the
// gateway-owned /.well-known/jwks route with the public keys of the
// gateway signing keyring, so anything the gateway signs — backend JWTs, A2A
// Agent Card signatures — can be verified by kid. The JWK Set document is
// generated by the policy engine and reaches this policy through the
// sdk/core/signing service the engine installs; the policy only relays it.
//
// It is a policy rather than an Envoy direct response for the same reason the
// A2A Agent Card is: a direct-response route has no ext_proc interaction, so
// the system observability policies would never see it, and the document could
// not answer a conditional GET. The route is an ordinary route whose cluster has
// no endpoints; this policy always terminates the chain at the request-header
// phase, so nothing is ever forwarded.
//
// The key set is read from the keyring on every request rather than captured
// when the instance is built. The keyring is installed once at engine startup,
// before any chain exists, so the two are equivalent today; reading it per
// request keeps the endpoint correct if that ordering ever changes.
package jwks

import (
	"context"
	"net/http"
	"strconv"
	"strings"

	policy "github.com/wso2/api-platform/sdk/core/policy/v1alpha2"
	"github.com/wso2/api-platform/sdk/core/signing"
)

const contentTypeJWKSet = "application/jwk-set+json"

// JWKSSystemPolicy answers the gateway JWKS route. It carries no state: every
// attachment shares one instance.
type JWKSSystemPolicy struct{}

var ins = &JWKSSystemPolicy{}

// GetPolicy returns the shared instance. The policy takes no parameters.
func GetPolicy(_ policy.PolicyMetadata, _ map[string]any) (policy.Policy, error) {
	return ins, nil
}

// GetPolicyV2 is an alias for GetPolicy, provided for compatibility with
// plugin registries that call GetPolicyV2 on all plugins.
func GetPolicyV2(metadata policy.PolicyMetadata, params map[string]any) (policy.Policy, error) {
	return GetPolicy(metadata, params)
}

// Mode declares the request-header phase only. The response is produced here,
// so there is no upstream response to inspect, and a JWKS request has no body.
func (p *JWKSSystemPolicy) Mode() policy.ProcessingMode {
	return policy.ProcessingMode{
		RequestHeaderMode:  policy.HeaderModeProcess,
		RequestBodyMode:    policy.BodyModeSkip,
		ResponseHeaderMode: policy.HeaderModeSkip,
		ResponseBodyMode:   policy.BodyModeSkip,
	}
}

// OnRequestHeaders always terminates the chain: with the key set, a 304, or a
// 405. It never forwards, because the route has no upstream to forward to.
func (p *JWKSSystemPolicy) OnRequestHeaders(
	_ context.Context,
	reqCtx *policy.RequestHeaderContext,
	_ map[string]any,
) policy.RequestHeaderAction {
	method := strings.ToUpper(reqCtx.Method)
	if method != http.MethodGet && method != http.MethodHead {
		return policy.ImmediateResponse{
			StatusCode: http.StatusMethodNotAllowed,
			Headers: map[string]string{
				"allow":         "GET, HEAD",
				"cache-control": "no-store",
			},
		}
	}

	body, etag := signing.JWKS()
	headers := map[string]string{
		"etag":                        etag,
		"cache-control":               "public, max-age=" + strconv.Itoa(int(signing.JWKSCacheMaxAge().Seconds())),
		"access-control-allow-origin": "*",
	}

	var values []string
	if reqCtx.Headers != nil {
		values = reqCtx.Headers.Get("if-none-match")
	}
	if ifNoneMatchSatisfied(values, etag) {
		return policy.ImmediateResponse{StatusCode: http.StatusNotModified, Headers: headers}
	}

	// HEAD gets the same answer: Envoy's local reply drops the body of a
	// response to a HEAD request itself, keeping the headers GET would carry.
	headers["content-type"] = contentTypeJWKSet
	return policy.ImmediateResponse{StatusCode: http.StatusOK, Headers: headers, Body: body}
}

// ifNoneMatchSatisfied reports whether an If-None-Match header selects the
// representation identified by etag. Comparison is weak (RFC 9110 §13.1.2): a
// "W/" prefix is ignored on both sides, "*" always matches, and every value of
// every occurrence of the header is considered.
func ifNoneMatchSatisfied(headerValues []string, etag string) bool {
	target := strings.TrimPrefix(etag, "W/")
	for _, headerValue := range headerValues {
		for _, candidate := range strings.Split(headerValue, ",") {
			candidate = strings.TrimSpace(candidate)
			if candidate == "*" || (candidate != "" && strings.TrimPrefix(candidate, "W/") == target) {
				return true
			}
		}
	}
	return false
}
