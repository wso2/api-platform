// The admin credential the operator generates for a gateway that has neither
// spec.adminCredentials nor basic-auth users in its values. It lives in a Secret in the
// gateway's namespace, created once and reused for the gateway's lifetime, and the
// gateway-controller reads the password from it as a mounted file.
const (
	// GeneratedAdminCredentialsLabel marks a Secret the operator generated. The operator
	// only ever reads a generated credential from a Secret that carries it, so a Secret a
	// user happens to create under the same name is never mistaken for one.
	GeneratedAdminCredentialsLabel      = "gateway.api-platform.wso2.com/admin-credentials"
	GeneratedAdminCredentialsLabelValue = "generated"
	// GeneratedAdminCredentialsGatewayAnnotation names the gateway the Secret belongs to.
	GeneratedAdminCredentialsGatewayAnnotation = "gateway.api-platform.wso2.com/gateway"
	// AdminCredentialsSecretAnnotation is set by the operator on a gateway (APIGateway or
	// Gateway API Gateway) that uses an operator-generated admin credential, naming the
	// Secret that holds it. It is informational: the operator finds the Secret by name and
	// label, and removes the annotation when the gateway stops using it.
	AdminCredentialsSecretAnnotation = "gateway.api-platform.wso2.com/admin-credentials-secret"

	GeneratedAdminUsernameKey = "username"
	GeneratedAdminPasswordKey = "password"

	generatedAdminSecretSuffix = "-admin-credentials"
	generatedPasswordLength    = 32
	generatedPasswordAlphabet  = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
	maxSecretNameLength        = 253
)

// GeneratedAdminSecretName returns the name of the Secret holding the operator-generated
// admin credential of the gateway named gatewayName. A name too long for a Secret is
// shortened and made unique with a hash of the full gateway name.
func GeneratedAdminSecretName(gatewayName string) string {
	name := gatewayName + generatedAdminSecretSuffix
	if len(name) <= maxSecretNameLength {
		return name
	}
	sum := sha256.Sum256([]byte(gatewayName))
	hash := hex.EncodeToString(sum[:])[:8]
	keep := maxSecretNameLength - len(generatedAdminSecretSuffix) - len(hash) - 1
	return gatewayName[:keep] + "-" + hash + generatedAdminSecretSuffix
}

// GeneratePassword returns a random password of 32 letters and digits drawn from
// crypto/rand.
func GeneratePassword() (string, error) {
	out := make([]byte, generatedPasswordLength)
	limit := big.NewInt(int64(len(generatedPasswordAlphabet)))
	for i := range out {
		n, err := rand.Int(rand.Reader, limit)
		if err != nil {
			return "", fmt.Errorf("generate admin password: %w", err)
		}
		out[i] = generatedPasswordAlphabet[n.Int64()]
	}
	return string(out), nil
}

// IsGeneratedAdminSecret reports whether secret is an operator-generated admin
// credential.
func IsGeneratedAdminSecret(secret *corev1.Secret) bool {
	return secret != nil && secret.Labels[GeneratedAdminCredentialsLabel] == GeneratedAdminCredentialsLabelValue
}

// ErrForeignAdminSecret is returned when a Secret has the generated admin credential's
// name but was not generated by the operator.
var ErrForeignAdminSecret = errors.New("secret was not generated by the gateway operator")

// GetGeneratedAdminSecret returns the operator-generated admin credential Secret of a
// gateway, or nil when it does not exist. A Secret with that name that the operator did
// not generate is an error: the operator neither uses nor overwrites it.
func GetGeneratedAdminSecret(ctx context.Context, c client.Client, namespace, gatewayName string) (*corev1.Secret, error) {
	name := GeneratedAdminSecretName(gatewayName)
	secret := &corev1.Secret{}
	if err := c.Get(ctx, types.NamespacedName{Namespace: namespace, Name: name}, secret); err != nil {
		if apierrors.IsNotFound(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("get generated admin credentials secret %s/%s: %w", namespace, name, err)
	}
	if !IsGeneratedAdminSecret(secret) {
		return nil, fmt.Errorf("secret %s/%s (label %s=%s is missing; rename it, or reference it from spec.adminCredentials): %w",
			namespace, name, GeneratedAdminCredentialsLabel, GeneratedAdminCredentialsLabelValue, ErrForeignAdminSecret)
	}
	return secret, nil
}

// GeneratedAdminCredentials returns the username and password from an operator-generated
// admin credential Secret, as the gateway-controller reads them from the mounted file. An
// empty value is an error, never a default.
func GeneratedAdminCredentials(secret *corev1.Secret) (username, password string, err error) {
	password = PasswordAsGatewayReadsIt(string(secret.Data[GeneratedAdminPasswordKey]), PasswordSourceFile)
	if password == "" {
		return "", "", fmt.Errorf("key %q in generated admin credentials secret %s/%s is empty",
			GeneratedAdminPasswordKey, secret.Namespace, secret.Name)
	}
	username = string(secret.Data[GeneratedAdminUsernameKey])
	if username == "" {
		username = DefaultAdminUsername
	}
	return username, password, nil
}
